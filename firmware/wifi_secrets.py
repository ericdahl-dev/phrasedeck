# PlatformIO pre-build script: writes src/wifi_secrets.h (gitignored) from an ini file with
# [wifi] ssid / password, PHRASEDECK_WIFI_INI or ~/.config/phrasedeck/panel-wifi.ini. Without the
# file (CI), both are empty and the panel skips Wi-Fi. The values never go into build flags or logs.
# configparser strips spaces around a value and keeps quotes: write `password = abc`, not "abc".
import configparser
import os

Import("env")  # noqa: F821 (PlatformIO's SCons global)

path = os.environ.get("PHRASEDECK_WIFI_INI", os.path.expanduser("~/.config/phrasedeck/panel-wifi.ini"))
ssid = password = ""
if os.path.exists(path):
    ini = configparser.ConfigParser(interpolation=None)
    ini.read(path)
    ssid = ini.get("wifi", "ssid", fallback="")
    password = ini.get("wifi", "password", fallback="")


def c_string(s):
    # Printable ASCII as is, " and \ escaped, anything else as UTF-8 octal escapes.
    return '"' + "".join(c if 32 <= ord(c) < 127 and c not in '"\\' else
                         ("\\" + c if c in '"\\' else "".join("\\%03o" % b for b in c.encode()))
                         for c in s) + '"'


header = os.path.join(env.subst("$PROJECT_SRC_DIR"), "wifi_secrets.h")  # noqa: F821
text = ("// Generated by wifi_secrets.py from %s. Not in git.\n#pragma once\n"
        "#define WIFI_SSID %s\n#define WIFI_PASSWORD %s\n") % (os.path.basename(path), c_string(ssid), c_string(password))
if not os.path.exists(header) or open(header).read() != text:
    if os.path.exists(header):
        os.remove(header)
    with os.fdopen(os.open(header, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "w") as f:
        f.write(text)
print("wifi_secrets: %s" % ("set" if ssid else "none; Wi-Fi off"))
